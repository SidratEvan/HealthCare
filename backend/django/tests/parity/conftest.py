"""Parity vectors: generated from the TypeScript on demand.

The vectors are tens of megabytes, so they are not committed. When one is
missing, or older than the TypeScript it comes from, it is regenerated by
running its generator with the repository's `tsx`. Node is required for this
suite, as it is for the rest of the repository; without it the suite fails
rather than passing on nothing.
"""

from __future__ import annotations

import json
import shutil
import subprocess
from pathlib import Path
from typing import Any

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[3]

#: Which TypeScript each vector file is generated from, for staleness.
SOURCES = {
    "queue": [REPO / "shared" / "domain" / "src" / "queue", REPO / "shared" / "domain" / "src" / "util"],
}


def _newest(paths: list[Path]) -> float:
    newest = 0.0
    for path in paths:
        files = path.rglob("*.ts") if path.is_dir() else [path]
        for file in files:
            newest = max(newest, file.stat().st_mtime)
    return newest


def _tsx() -> str:
    for candidate in (
        REPO / "backend" / "api" / "node_modules" / ".bin" / "tsx.cmd",
        REPO / "backend" / "api" / "node_modules" / ".bin" / "tsx",
    ):
        if candidate.exists():
            return str(candidate)
    found = shutil.which("tsx")
    if found is None:
        raise RuntimeError("tsx is needed to generate parity vectors: run `pnpm install` at the repository root.")
    return found


def load_vectors(name: str) -> dict[str, Any]:
    target = HERE / "vectors" / f"{name}.json"
    generator = HERE / f"generate_{name}_vectors.ts"
    stale = not target.exists() or target.stat().st_mtime < max(
        _newest(SOURCES.get(name, [])), generator.stat().st_mtime
    )
    if stale:
        subprocess.run([_tsx(), str(generator)], cwd=REPO, check=True)
    return json.loads(target.read_text(encoding="utf8"))
